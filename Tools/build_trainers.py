#!/usr/bin/env python3
"""Build Data/TrainerData.lua from trainer lists pasted out of the game.

    python3 -I Tools/build_trainers.py Tools/trainer_raw Data/TrainerData.lua

Each file in Tools/trainer_raw is named after the profession key (leatherworking.txt,
tailoring.txt, ...) and holds two comma-separated lists copied from the trainer window:

    # optional comment lines
    Handstitched Leather Pants, Camp Tent, ..., Leatherworking, ...
    ---
    Leatherworking 15, Leatherworking 20, ..., Leatherworking 50, ...

The first list is every service the trainer offers, the second the skill each one needs,
in the same order. Entries named after the profession itself are rank trainings
(Journeyman, Expert, ...). A requirement of "??" means the game didn't show it.

Mark a list as the profession's complete trainer offering by adding a line "complete".
Then recipes the data thinks are trainer-taught but that aren't on the list are treated
as not taught by trainers (quest, specialization, or other sources).
"""
import os
import re
import sys

PROF_NAMES = {
    "alchemy": "Alchemy", "blacksmithing": "Blacksmithing", "enchanting": "Enchanting",
    "engineering": "Engineering", "leatherworking": "Leatherworking", "tailoring": "Tailoring",
    "cooking": "Cooking",
}


def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def parse(path, prof):
    lines = [l.strip() for l in open(path, encoding="utf-8") if l.strip() and not l.strip().startswith("#")]
    complete = any(l.lower() == "complete" for l in lines)
    lines = [l for l in lines if l.lower() != "complete"]
    if "---" not in lines:
        raise SystemExit(f"{path}: expected a '---' line between the two lists")
    sep = lines.index("---")
    names = [n.strip() for n in " ".join(lines[:sep]).split(",") if n.strip()]
    reqs = [r.strip() for r in " ".join(lines[sep + 1:]).split(",") if r.strip()]
    if len(names) != len(reqs):
        raise SystemExit(f"{path}: {len(names)} services but {len(reqs)} requirements")
    pname = PROF_NAMES[prof]
    recipes, ranks = {}, []
    for name, req in zip(names, reqs):
        m = re.fullmatch(re.escape(pname) + r"\s+(\d+|\?\?)", req)
        if not m:
            raise SystemExit(f"{path}: can't read requirement {req!r} for {name!r}")
        skill = None if m.group(1) == "??" else int(m.group(1))
        if name == pname:
            ranks.append(skill)
        elif skill is not None:
            recipes[name] = min(skill, recipes.get(name, skill))
    return recipes, ranks, complete


def main():
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    src, out = sys.argv[1], sys.argv[2]
    blocks = []
    for fn in sorted(os.listdir(src)):
        prof, ext = os.path.splitext(fn)
        if ext != ".txt" or prof not in PROF_NAMES:
            continue
        recipes, ranks, complete = parse(os.path.join(src, fn), prof)
        rows = "\n".join(f"        [{lua_str(n)}] = {s}," for n, s in sorted(recipes.items(), key=lambda x: (x[1], x[0])))
        # ranks in skill order (unknown "??" last), whatever order the paste was in
        ranks = sorted(ranks, key=lambda r: (r is None, r or 0))
        rank_txt = ", ".join("nil" if r is None else str(r) for r in ranks)
        blocks.append(
            f"D.trainerData.{prof} = {{\n"
            f"    complete = {'true' if complete else 'false'},\n"
            f"    ranks = {{ {rank_txt} }}, -- skill needed to train each next rank\n"
            f"    recipes = {{\n{rows}\n    }},\n}}\n")
        print(f"{prof}: {len(recipes)} recipes, ranks {ranks}, complete={complete}", file=sys.stderr)
    with open(out, "w", encoding="utf-8") as f:
        f.write("-- GENERATED by Tools/build_trainers.py from Tools/trainer_raw/*.txt (trainer lists from the game).\n")
        f.write("-- recipes: name -> skill needed to learn it from the trainer.\n")
        f.write("local _, ns = ...\nlocal D = ns.Data\n\nD.trainerData = {}\n\n")
        f.write("\n".join(blocks))


if __name__ == "__main__":
    main()
